"""Operaciones aritméticas básicas de la calculadora.

Cada función recibe dos números y devuelve el resultado del cálculo.
No interactúan con el usuario: son funciones puras.
"""


def sumar(a, b):
    """Devuelve la suma de a y b."""
    return a + b


def restar(a, b):
    """Devuelve la resta de a y b."""
    return a - b


def multiplicar(a, b):
    """Devuelve la multiplicacion de a y b."""
    return a * b


def dividir(a, b):
    """Devuelve la division de a entre b."""
    return a / b